static void fb_set_pixel(uint8_t *fb, int width, int height, int x, int y, bool on)
{
    if (x < 0 || y < 0 || x >= width || y >= height) {
        return;
    }
    const int page = y / 8;
    const int bit = y % 8;
    const int idx = page * width + x;
    if (on) {
        fb[idx] |= (uint8_t)(1 << bit);
    } else {
        fb[idx] &= (uint8_t)~(1 << bit);
    }
}

void oled_font_clear(uint8_t *fb, int width, int height)
{
    memset(fb, 0, (size_t)(width * height / 8));
}

void oled_font_draw_str(uint8_t *fb, int x, int y, int width, int height, const char *str)
{
    if (str == NULL) {
        return;
    }

    while (*str != '\0' && x < width) {
        unsigned char c = (unsigned char)*str++;
        if (c < FONT_FIRST || c > FONT_LAST) {
            c = '?';
        }
        const uint8_t *glyph = &s_font5x7[(c - FONT_FIRST) * FONT_W];
        const int top = y - (FONT_H - 1);

        for (int col = 0; col < FONT_W && (x + col) < width; col++) {
            uint8_t col_data = glyph[col];
            for (int row = 0; row < FONT_H; row++) {
                if (col_data & (1 << row)) {
                    fb_set_pixel(fb, width, height, x + col, top + row, true);
                }
            }
        }
        x += FONT_W + FONT_GAP;
    }
}
